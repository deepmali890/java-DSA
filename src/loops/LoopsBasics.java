package loops;

// ============================================================
// Loops Basics in Java
// ============================================================

/*

Loops are used
to execute a block of code
repeatedly until
a condition becomes false.

Loops help us avoid
writing the same code again and again.

*/


public class LoopsBasics {

    public static void main(String[] args) {



        // ============================================================
        // Types of Loops in Java
        // ============================================================

        /*

           1. for loop
           2. while loop
           3. do-while loop

        */



        // ============================================================
        // Simple Example of Loop
        // ============================================================

        /*
           Printing "Hello Java"
           5 times using for loop.
        */

        for (int i = 1; i <= 5; i++) {

            System.out.println("Hello Java");

        }

    }
}



/*

Output:

Hello Java
Hello Java
Hello Java
Hello Java
Hello Java

*/


// ============================================================
// Explanation
// ============================================================

/*

1. Loops execute code repeatedly.

--------------------------------------------------

2. for loop
   Used when number of repetitions is known.

--------------------------------------------------

3. while loop
   Used when condition is important.

--------------------------------------------------

4. do-while loop
   Executes at least one time.

--------------------------------------------------

5. i++
   Increases value by 1.

*/
