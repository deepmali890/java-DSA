package basics;// ============================================================
// 3. Print Pattern in Java
// ============================================================

/*
Pattern:

*****
****
***
**
*

We use System.out.println() so that each pattern
prints on a new line.
*/


// Example:

public class PrintPattern {

    public static void main(String[] args) {

        System.out.println("*****");
        System.out.println("****");
        System.out.println("***");
        System.out.println("**");
        System.out.println("*");

    }
}



/*
Output:

*****
****
***
**
*

*/